#!/usr/bin/env node
/**
 * Baseline screenshots for UI refactor
 * Captures current UI state before MD3 refactor
 */
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');

const BASE_URL = process.env.BASE_URL || 'http://localhost:3000';
const OUTPUT_DIR = path.resolve(process.cwd(), 'docs/ui-baseline');

const PAGES = [
  { url: '/', slug: 'homepage' },
  { url: '/login', slug: 'login' },
  { url: '/submit', slug: 'submit' },
  { url: '/tasks', slug: 'tasks' },
  { url: '/settings/account', slug: 'settings-account' },
  { url: '/settings/cookies', slug: 'settings-cookies' },
  // Lobby pages with a fake code — shows current state/error/loading
  { url: '/lobby/TEST-CODE', slug: 'lobby-waiting' },
  { url: '/lobby/TEST-CODE/map', slug: 'lobby-map' },
  { url: '/lobby/TEST-CODE/select', slug: 'lobby-select' },
  { url: '/lobby/TEST-CODE/bans', slug: 'lobby-bans' },
];

const VIEWPORTS = {
  mobile: { width: 375, height: 800 },
  desktop: { width: 1440, height: 900 },
};

async function main() {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  const browser = await chromium.launch({ headless: true });
  const results = [];
  const errors = [];

  for (const pageConfig of PAGES) {
    for (const [viewportName, viewport] of Object.entries(VIEWPORTS)) {
      const context = await browser.newContext({
        viewport,
        colorScheme: 'dark', // Current app default is dark mode
      });
      const page = await context.newPage();

      const fullUrl = `${BASE_URL}${pageConfig.url}`;
      const filename = `${pageConfig.slug}-dark-${viewportName}.png`;
      const filepath = path.join(OUTPUT_DIR, filename);

      try {
        const response = await page.goto(fullUrl, {
          waitUntil: 'networkidle',
          timeout: 15000,
        });

        // Wait a bit for any client-side hydration/animations
        await page.waitForTimeout(1500);

        await page.screenshot({
          path: filepath,
          fullPage: true,
        });

        results.push({
          url: pageConfig.url,
          viewport: viewportName,
          status: response?.status() ?? 'unknown',
          file: filepath,
        });
        console.log(`✓ ${filename} (${response?.status() ?? 'unknown'})`);
      } catch (error) {
        errors.push({
          url: pageConfig.url,
          viewport: viewportName,
          error: error.message,
        });
        console.error(`✗ ${filename}: ${error.message}`);
      } finally {
        await context.close();
      }
    }
  }

  await browser.close();

  // Generate README
  const readme = generateReadme(results, errors);
  fs.writeFileSync(path.join(OUTPUT_DIR, 'README.md'), readme);
  console.log(`\n✓ Baseline README written to ${path.join(OUTPUT_DIR, 'README.md')}`);

  if (errors.length > 0) {
    console.error(`\n⚠ ${errors.length} screenshot(s) failed`);
    process.exit(1);
  }
}

function generateReadme(results, errors) {
  const timestamp = new Date().toISOString();
  return `# UI Baseline — Pre-MD3 Refactor

Generated: ${timestamp}
Branch: refactor/ui-material-design
Base URL: ${BASE_URL}

## Purpose
These screenshots document the UI state before the Material Design 3 refactor. Use them for visual comparison after each phase.

## Screenshots

| Page | Mobile (375px) | Desktop (1440px) |
|------|----------------|------------------|
${results
  .filter((r) => r.viewport === 'mobile')
  .map((r) => {
    const desktop = results.find(
      (d) => d.url === r.url && d.viewport === 'desktop'
    );
    const slug = path.basename(r.file, '-dark-mobile.png');
    return `| ${r.url} | [mobile](${slug}-dark-mobile.png) | [desktop](${slug}-dark-desktop.png) |`;
  })
  .join('\n')}

## Failed Captures
${errors.length === 0 ? 'None.' : errors.map((e) => `- \`${e.url}\` (${e.viewport}): ${e.error}`).join('\n')}

## Notes
- All screenshots captured in dark mode (current app default)
- Lobby pages use placeholder code \`TEST-CODE\`; state reflects loading/error
- Generated by \`scripts/baseline-screenshots.js\`
`;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
